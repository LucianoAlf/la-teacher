def sb_headers(prefer: Optional[str] = None) -> Dict[str, str]:
    if not SUPABASE_KEY:
        raise RuntimeError("LAREPORT_SUPABASE_SERVICE_ROLE missing")
    h = {
        "apikey": SUPABASE_KEY,
        "Authorization": f"Bearer {SUPABASE_KEY}",
        "Content-Type": "application/json",
    }
    if prefer:
        h["Prefer"] = prefer
    return h


def sb_get(path: str, params: Dict[str, str]) -> Any:
    r = requests.get(f"{SUPABASE_URL}{path}", headers=sb_headers(), params=params, timeout=_HTTP_TIMEOUT)
    if r.status_code >= 400:
        raise RuntimeError(f"Supabase GET {path} {r.status_code}: {r.text[:500]}")
    return r.json()


def sb_post(
    path: str,
    body: Any,
    prefer: Optional[str] = None,
    timeout: tuple[int, int] = _HTTP_TIMEOUT,
) -> requests.Response:
    return requests.post(f"{SUPABASE_URL}{path}", headers=sb_headers(prefer), json=body, timeout=timeout)


def sb_patch(path: str, params: Dict[str, str], body: Any, prefer: Optional[str] = None) -> requests.Response:
    return requests.patch(f"{SUPABASE_URL}{path}", headers=sb_headers(prefer), params=params, json=body, timeout=_HTTP_TIMEOUT)


def _readback_fail_closed(professor_id: Any) -> dict[str, Any]:
    return sanear_readback_para_preview(
        None,
        professor_id=professor_id,
        roster_ids=set(),
    )


def _sanear_readback_com_roster_real(result: Any, payload: dict[str, Any]) -> dict[str, Any]:
    """Busca o roster autoritativo antes de liberar um preview de read-back."""
    try:
        professor_id = payload.get("p_professor_id")
        if isinstance(professor_id, bool) or not isinstance(professor_id, int):
            return _readback_fail_closed(professor_id)
        if not isinstance(result, dict):
            return _readback_fail_closed(professor_id)
        trunk = result.get("tronco")
        raw_slices = result.get("fatias")
        if not isinstance(trunk, dict) or not isinstance(raw_slices, list) or not raw_slices:
            return _readback_fail_closed(professor_id)
        aula_id = trunk.get("aula_id")
        trunk_professor_id = trunk.get("professor_id")
        if (
            isinstance(aula_id, bool)
            or not isinstance(aula_id, int)
            or isinstance(trunk_professor_id, bool)
            or trunk_professor_id != professor_id
        ):
            return _readback_fail_closed(professor_id)

        context_rows = sb_get(
            "/rest/v1/vw_fabio_aulas_contexto",
            {
                "select": "aula_local_id,professor_id,aluno_id",
                "aula_local_id": f"eq.{aula_id}",
                "professor_id": f"eq.{professor_id}",
            },
        )
        if not isinstance(context_rows, list) or not context_rows:
            return _readback_fail_closed(professor_id)
        roster_ids: set[int] = set()
        for row in context_rows:
            if not isinstance(row, dict):
                return _readback_fail_closed(professor_id)
            aluno_id = row.get("aluno_id")
            if (
                row.get("aula_local_id") != aula_id
                or row.get("professor_id") != professor_id
                or isinstance(aluno_id, bool)
                or not isinstance(aluno_id, int)
            ):
                return _readback_fail_closed(professor_id)
            roster_ids.add(aluno_id)
        if not roster_ids:
            return _readback_fail_closed(professor_id)
        return sanear_readback_para_preview(
            result,
            professor_id=professor_id,
            roster_ids=roster_ids,
        )
    except Exception:
        return _readback_fail_closed(payload.get("p_professor_id"))


class FabioBridgeBackend(FabioWhatsappBackend):
    """Guarded service-role adapter used by actions and the reconciler."""

    def __init__(self, bucket: str = "fabio-audios") -> None:
        self.bucket = bucket

    def rpc(self, name: str, payload: dict[str, Any]) -> Any:
        response = sb_post(f"/rest/v1/rpc/{name}", payload)
        if response.status_code >= 400:
            raise RuntimeError(f"{name}_rpc_failed_{response.status_code}")
        result = response.json() if response.content else None
        if name != "fabio_registro_completo":
            return result
        return _sanear_readback_com_roster_real(result, payload)

    @staticmethod
    def _extension(mime: str) -> str:
        base = (mime or "").split(";", 1)[0].strip().lower()
        return {
            "audio/ogg": "ogg",
            "audio/opus": "ogg",
            "audio/webm": "webm",
            "audio/mp4": "m4a",
            "audio/m4a": "m4a",
            "audio/mpeg": "mp3",
            "audio/wav": "wav",
            "audio/x-wav": "wav",
        }.get(base, "ogg")

    def download_audio(self, media_url: str, max_bytes: int) -> tuple[bytes, str, str]:
        response = requests.get(media_url, timeout=_HTTP_TIMEOUT, stream=True)
        if response.status_code >= 400:
            raise RuntimeError(f"media_download_failed_{response.status_code}")
        content_length = response.headers.get("Content-Length")
        if content_length:
            try:
                if int(content_length) > max_bytes:
                    raise RuntimeError("audio_too_large")
            except ValueError:
                pass
        chunks = bytearray()
        try:
            for chunk in response.iter_content(chunk_size=64 * 1024):
                if not chunk:
                    continue
                chunks.extend(chunk)
                if len(chunks) > max_bytes:
                    raise RuntimeError("audio_too_large")
        finally:
            response.close()
        mime = response.headers.get("Content-Type") or "audio/ogg"
        return bytes(chunks), self._extension(mime), mime

    def _storage_url(self, storage_path: str) -> str:
        from urllib.parse import quote
        return f"{SUPABASE_URL}/storage/v1/object/{self.bucket}/{quote(storage_path, safe='/')}"

    def upload_audio(self, storage_path: str, content: bytes, mime: str) -> None:
        headers = sb_headers()
        headers.update({"Content-Type": mime or "audio/ogg", "x-upsert": "false"})
        response = requests.post(self._storage_url(storage_path), headers=headers, data=content, timeout=_HTTP_TIMEOUT)
        if response.status_code >= 400:
            raise RuntimeError(f"storage_upload_failed_{response.status_code}")

    def remove_audio(self, storage_path: str) -> None:
        # Supabase Storage remove is a bulk-delete operation: the bucket is
        # the route and the exact object key travels in `prefixes`.
        response = requests.delete(
            f"{SUPABASE_URL}/storage/v1/object/{self.bucket}",
            headers=sb_headers(),
            json={"prefixes": [storage_path]},
            timeout=_HTTP_TIMEOUT,
        )
        if response.status_code not in {200, 204, 404}:
            raise RuntimeError(f"storage_remove_failed_{response.status_code}")

    def send_preview(self, action_id: str, professor_id: int, content: str) -> dict[str, Any]:
        """Persist and deliver one canonical preview, replay-safe by action id."""
        action_id = str(action_id or "").strip()
        content = str(content or "").strip()
        if not action_id or not content:
            raise RuntimeError("preview_invalido")
        professor_id = int(professor_id)
        dedupe_key = f"fabio-preview:{action_id}"

        def existing_rows() -> list[dict[str, Any]]:
            return sb_get("/rest/v1/fabio_chat_mensagens", {
                "select": "id,role,professor_id,channel,content,wa_message_id,fabio_done_at",
                "wa_message_id": f"eq.{dedupe_key}",
                "limit": "1",
            })

        rows = existing_rows()
        persisted_before_this_attempt = bool(rows)
        if rows:
            row = rows[0]
            if (
                row.get("role") != "fabio"
                or int(row.get("professor_id") or 0) != professor_id
                or row.get("channel") != "whatsapp"
                or str(row.get("content") or "") != content
            ):
                raise RuntimeError("preview_contexto_conflitante")
            if row.get("fabio_done_at"):
                return {"ok": True, "ja_enviado": True, "wa_message_id": dedupe_key}
            # The row is durable before transport. On replay an unfinished row
            # can mean "sent, crashed before close", so never send it again.
            if persisted_before_this_attempt:
                raise RuntimeError("preview_entrega_incerta")
        else:
            response = sb_post(
                "/rest/v1/fabio_chat_mensagens",
                {
                    "identidade_tipo": "professor",
                    "role": "fabio",
                    "kind": "text",
                    "content": content,
                    "channel": "whatsapp",
                    "professor_id": professor_id,
                    "wa_message_id": dedupe_key,
                },
                prefer="return=representation",
            )
            if response.status_code == 409:
                rows = existing_rows()
                if not rows:
                    raise RuntimeError("preview_outbox_conflito")
                row = rows[0]
                if (
                    row.get("role") != "fabio"
                    or int(row.get("professor_id") or 0) != professor_id
                    or row.get("channel") != "whatsapp"
                    or str(row.get("content") or "") != content
                ):
                    raise RuntimeError("preview_contexto_conflitante")
                if row.get("fabio_done_at"):
                    return {"ok": True, "ja_enviado": True, "wa_message_id": dedupe_key}
                raise RuntimeError("preview_entrega_incerta")
            elif response.status_code >= 400:
                raise RuntimeError(f"preview_outbox_failed_{response.status_code}")
            else:
                data = response.json()
                row = data[0] if isinstance(data, list) and data else None
            if not isinstance(row, dict) or not row.get("id"):
                raise RuntimeError("preview_outbox_incompleto")

        transport_id = send_whatsapp_text(professor_id, content)
        if not transport_id:
            raise RuntimeError("preview_transporte_sem_id")
        marked = sb_patch(
            "/rest/v1/fabio_chat_mensagens",
            {"id": f"eq.{row['id']}"},
            {"fabio_done_at": now_iso()},
            prefer="return=representation",
        )
        if marked.status_code >= 400:
            raise RuntimeError(f"preview_outbox_close_failed_{marked.status_code}")
        return {"ok": True, "ja_enviado": False, "wa_message_id": dedupe_key, "transport_id": transport_id}


