def run_hermes_api(prompt: str, professor_id: Optional[int] = None, channel: Optional[str] = None) -> str:
    if not HERMES_API_KEY:
        raise RuntimeError("FABIO_HERMES_API_KEY/API_SERVER_KEY missing")
    headers = {
        "Authorization": f"Bearer {HERMES_API_KEY}",
        "Content-Type": "application/json",
    }
    body = {
        "model": HERMES_API_MODEL,
        "messages": [{"role": "user", "content": prompt}],
        "stream": False,
    }
    t0 = time.monotonic()
    r = requests.post(HERMES_API_URL, headers=headers, json=body, timeout=HERMES_API_TIMEOUT)
    dt = round(time.monotonic() - t0, 2)
    if r.status_code >= 400:
        raise RuntimeError(f"hermes api http={r.status_code} elapsed={dt}s: {r.text[:800]}")
    data = r.json()
    out = (((data.get("choices") or [{}])[0].get("message") or {}).get("content") or "").strip()
    if not out:
        raise RuntimeError(f"hermes api returned empty response elapsed={dt}s")
    log("hermes_api_ok", professor_id=professor_id, channel=channel, elapsed_s=dt, model=HERMES_API_MODEL)
    return out[-4000:]


def run_hermes_oneshot(prompt: str) -> str:
    cmd = HERMES_CMD.split() + ["--accept-hooks"]
    if CHAT_SKILLS:
        cmd += ["--skills", CHAT_SKILLS]
    cmd += ["--oneshot", prompt]
    env = os.environ.copy()
    env.setdefault("HERMES_HOME", str(HERMES_HOME))
    env.setdefault("HOME", str(ROOT_DIR))
    proc = subprocess.run(
        cmd,
        cwd=str(ROOT_DIR),
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=int(os.getenv("FABIO_CHAT_HERMES_TIMEOUT", "180")),
    )
    if proc.returncode != 0:
        raise RuntimeError(f"hermes oneshot rc={proc.returncode}: {proc.stderr[-1000:]}")
    out = proc.stdout.strip()
    if not out:
        raise RuntimeError("hermes oneshot returned empty response")
    return out[-4000:]


def whatsapp_send_payload(number: str, text: str) -> Dict[str, Any]:
    """Build UAZAPI send/text payload with typing indicator delay.

    UAZAPI `delay` is milliseconds and shows "Digitando..." during the wait.
    Keep it short: this is UX polish, not artificial waiting.
    """
    base_delay = int(os.getenv("FABIO_WHATSAPP_TYPING_DELAY_MS", "0"))
    max_delay = int(os.getenv("FABIO_WHATSAPP_TYPING_DELAY_MAX_MS", "1000"))
    per_char = int(os.getenv("FABIO_WHATSAPP_TYPING_DELAY_PER_CHAR_MS", "0"))
    delay = base_delay
    if per_char > 0:
        delay = max(delay, len(text or "") * per_char)
    delay = max(0, min(delay, max_delay))
    payload = {"number": number, "text": text, "readchat": True}
    if delay > 0:
        payload["delay"] = int(delay)
    return payload

