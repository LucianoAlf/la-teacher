def process_one() -> bool:
    first_row = claim_next_message()
    if not first_row:
        return False
    log("processing_message", id=first_row.get("id"), professor_id=first_row.get("professor_id"), usuario_id=first_row.get("usuario_id"), identidade_tipo=first_row.get("identidade_tipo"), channel=first_row.get("channel"))
    if first_row.get("channel") == "whatsapp":
        try:
            send_whatsapp_presence_for_row(first_row, "composing")
        except Exception as e:
            log("whatsapp_presence_failed", id=first_row.get("id"), error=str(e)[:500])
    batch = collect_message_batch(first_row)
    if first_row.get("channel") == "whatsapp":
        batch = [hydrate_audio_row(item) if item.get("kind") == "audio" else item for item in batch]
    row = merge_message_batch(batch)
    if row.get("channel") == "whatsapp" and row.get("kind") != "audio" and not (
        row.get("content") or row.get("media_extracted_text")
    ):
        _send_row_whatsapp(row, AVISO_MIDIA_SEM_SUPORTE.format(tipo=row.get("kind") or "arquivo"))
        for mid in row.get("_batch_ids") or [str(first_row["id"])]:
            mark_done(str(mid))
        log("processed_unsupported_media", id=first_row.get("id"), kind=row.get("kind"))
        return True
    text = row.get("content") or row.get("media_extracted_text") or ""
    consulta_pendencias = _tem_intencao_explicita_de_pendencias(text)
    pergunta_pendencias_relatada = _tem_pergunta_de_pendencias_apenas_relatada(text)
    if not consulta_pendencias and not pergunta_pendencias_relatada and try_handle_whatsapp_action(row) is True:
        for mid in row.get("_batch_ids") or [str(first_row["id"])]:
            mark_done(str(mid))
        log("processed_whatsapp_action", id=first_row.get("id"), batch_count=row.get("_batch_count", 1))
        return True
    if _admin_deep_analysis_intent(row):
        answer = "Fechado, Alf. Vou rodar esse pente-fino em paralelo agora — carteira, presença/jornada, registros e retenção — e já te devolvo uma lista curta com evidência, sem achismo."
        insert_fabio_response_for_row(row, answer, row.get("channel") or "app")
        if row.get("channel") == "whatsapp":
            try:
                _send_row_whatsapp(row, answer)
            except Exception as e:
                log("whatsapp_send_failed", id=first_row.get("id"), error=str(e)[:500])
        for mid in row.get("_batch_ids") or [str(first_row["id"])]:
            mark_done(str(mid))
        start_async_admin_analysis(row)
        log("processed_message_async_admin_analysis", id=first_row.get("id"), batch_count=row.get("_batch_count", 1))
        return True

    try:
        answer, answer_source = generate_answer(row)
        log("answer_generated", id=first_row.get("id"), source=answer_source, batch_count=row.get("_batch_count", 1))
    except Exception as e:
        log("hermes_generation_failed", id=first_row.get("id"), error=str(e)[:500])
        answer = "Tive um erro ao processar sua mensagem agora. Pode me mandar de novo em instantes?"
    insert_fabio_response_for_row(row, answer, row.get("channel") or "app")
    if row.get("channel") == "whatsapp":
        try:
            if (row.get("identidade_tipo") or "professor") == "admin":
                phone = admin_phone(int(row["usuario_id"]))
                if not phone:
                    raise RuntimeError("admin_phone_missing")
                r = requests.post(
                    f"{UAZAPI_URL}/send/text",
                    headers={"Content-Type": "application/json", "token": UAZAPI_TOKEN},
                    json=whatsapp_send_payload(phone, answer),
                    timeout=_HTTP_TIMEOUT,
                )
                if r.status_code >= 400:
                    raise RuntimeError(f"uazapi send/text admin {r.status_code}: {r.text[:500]}")
                log("whatsapp_sent", usuario_id=row.get("usuario_id"), phone_tail=phone[-4:], typing_delay_ms=whatsapp_send_payload(phone, answer).get("delay", 0))
            else:
                send_whatsapp_text(int(row["professor_id"]), answer)
        except Exception as e:
            log("whatsapp_send_failed", id=first_row.get("id"), error=str(e)[:500])
    for mid in row.get("_batch_ids") or [str(first_row["id"])]:
        mark_done(str(mid))
    log("processed_message", id=first_row.get("id"), batch_count=row.get("_batch_count", 1))
    return True


class Handler(BaseHTTPRequestHandler):
    server_version = "FabioChatBridge/1.0"

    def _send(self, status: int, payload: Dict[str, Any]) -> None:
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, fmt: str, *args: Any) -> None:
        log("http", remote=self.client_address[0], message=fmt % args)

    def do_GET(self) -> None:
        parsed = urlparse(self.path)
        if parsed.path == "/health":
            self._send(200, {"ok": True, "agent": "fabio-chat-bridge"})
        else:
            self._send(404, {"ok": False, "error": "not_found"})

    def do_POST(self) -> None:
        parsed = urlparse(self.path)
        expected = f"/webhook/uazapi/{BRIDGE_SECRET}"
        if not BRIDGE_SECRET or parsed.path != expected:
            self._send(404, {"ok": False, "error": "not_found"})
            return
        length = min(int(self.headers.get("Content-Length") or 0), 1024 * 1024)
        raw = self.rfile.read(length)
        try:
            body = json.loads(raw.decode("utf-8")) if raw else {}
        except Exception:
            self._send(400, {"ok": False, "error": "invalid_json"})
            return
        # Ack fast to avoid UAZAPI retries; process ingestion in this request (cheap).
        try:
            # Todo descarte deixa rastro. Antes estes returns eram mudos: 200
            # para a UAZAPI, nada no log, nada no banco -- e nao havia como
            # saber depois que a mensagem existiu.
            if is_ignorable_uazapi(body):
                data = get_data(body)
                log(
                    "webhook_ignorado",
                    motivo="evento_ignoravel",
                    evento=str(body.get("EventType") or body.get("event_type") or body.get("type") or body.get("event") or "")[:40],
                    from_me=bool(data.get("fromMe")),
                    grupo=bool(data.get("isGroup")),
                    por_api=bool(data.get("wasSentByApi")),
                    tem_data=bool(data),
                )
                self._send(200, {"ok": True, "status": "ignored"})
                return
            phone = extract_phone(body)
            text = extract_text(body)
            wa_id = extract_message_id(body)
            if not phone:
                log("webhook_ignorado", motivo="sem_telefone", tem_texto=bool(text), tem_wa_id=bool(wa_id))
                self._send(200, {"ok": True, "status": "ignored_missing_phone_or_text"})
                return
            if not text:
                midia = extract_media_kind(body)
                log("webhook_sem_texto", midia=midia or "desconhecida", phone_tail=phone[-4:], tem_wa_id=bool(wa_id))
                # O ACK so sai depois da entrada duravel no inbox. A
                # transcricao fica para depois do claim em process_one().
                queued = ingest_media_message(body, phone, wa_id, midia)
                self._send(200, {"ok": True, **queued})
                return
            identity = resolve_identity_by_phone(phone)
            inserted = insert_identity_message(identity, text, "whatsapp", wa_id)
            self._send(200, {"ok": True, "status": "queued", "duplicate": bool(inserted.get("duplicate")), "tipo": identity.get("tipo")})
            log("whatsapp_ingested", professor_id=identity.get("professor_id"), usuario_id=identity.get("usuario_id"), identidade_tipo=identity.get("tipo"), phone_tail=phone[-4:], duplicate=bool(inserted.get("duplicate")))
        except Exception as e:
            log("webhook_ingest_failed", error=str(e)[:500])
            self._send(200, {"ok": False, "status": "error"})


def serve() -> None:
    httpd = ThreadingHTTPServer(("0.0.0.0", PORT), Handler)
    log("http_listening", port=PORT)
    httpd.serve_forever()


def poll_loop(stop: threading.Event) -> None:
    log("poller_started", interval=POLL_INTERVAL)
    while not stop.is_set():
        try:
            did = process_one()
            if not did:
                stop.wait(POLL_INTERVAL)
        except Exception as e:
            log("poller_error", error=str(e)[:500])
            stop.wait(max(POLL_INTERVAL, 5))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--once", action="store_true", help="process one queued message and exit")
    parser.add_argument("--health", action="store_true")
    args = parser.parse_args()
    if args.health:
        print(json.dumps({"ok": bool(SUPABASE_KEY), "port": PORT, "uazapi_token": bool(UAZAPI_TOKEN), "secret": bool(BRIDGE_SECRET)}))
        return 0
    if args.once:
        return 0 if process_one() else 2
    stop = threading.Event()
    t = threading.Thread(target=poll_loop, args=(stop,), daemon=True)
    t.start()
    serve()
    return 0


