def collect_message_batch(first_row: Dict[str, Any]) -> list[Dict[str, Any]]:
    """Debounce bursty professor/admin chat and claim follow-up bubbles."""
    batch = [first_row]
    debounce_seconds = MESSAGE_DEBOUNCE_SECONDS
    if (first_row.get("channel") or "app") == "whatsapp":
        debounce_seconds = float(os.getenv("FABIO_CHAT_WHATSAPP_DEBOUNCE_SECONDS", "2"))
    if debounce_seconds > 0:
        time.sleep(debounce_seconds)
    filters = {
        "select": "id,identidade_tipo,usuario_id,professor_id,role,kind,content,media_extracted_text,channel,wa_message_id,criado_em",
        "role": "eq.professor",
        "fabio_seen_at": "is.null",
        "identidade_tipo": f"eq.{first_row.get('identidade_tipo') or 'professor'}",
        "channel": f"eq.{first_row.get('channel') or 'app'}",
        "criado_em": f"gte.{first_row.get('criado_em')}",
        "order": "criado_em.asc",
        "limit": str(max(0, MESSAGE_BATCH_LIMIT - 1)),
    }
    if (first_row.get("identidade_tipo") or "professor") == "admin":
        filters["usuario_id"] = f"eq.{int(first_row['usuario_id'])}"
    else:
        filters["professor_id"] = f"eq.{int(first_row['professor_id'])}"
    rows = sb_get("/rest/v1/fabio_chat_mensagens", filters)
    for row in rows or []:
        if row.get("id") == first_row.get("id"):
            continue
        claimed = _claim_specific_message(row)
        if claimed:
            batch.append(claimed)
    if len(batch) > 1:
        log("message_batch_collected", first_id=first_row.get("id"), count=len(batch), ids=[r.get("id") for r in batch])
    return batch


def merge_message_batch(batch: list[Dict[str, Any]]) -> Dict[str, Any]:
    if not batch:
        raise ValueError("empty message batch")
    if len(batch) == 1:
        return batch[0]
    merged = dict(batch[0])
    parts = []
    media_parts = []
    for row in batch:
        content = (row.get("content") or "").strip()
        media_text = (row.get("media_extracted_text") or "").strip()
        if content:
            parts.append(content)
        if media_text:
            media_parts.append(media_text)
    merged["content"] = "\n".join(parts).strip()
    merged["media_extracted_text"] = "\n".join(media_parts).strip() or None
    merged["_batch_ids"] = [str(r.get("id")) for r in batch]
    merged["_batch_count"] = len(batch)
    return merged


