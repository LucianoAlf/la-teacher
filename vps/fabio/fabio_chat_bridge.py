def claim_next_message() -> Optional[Dict[str, Any]]:
    select_cols = "id,identidade_tipo,usuario_id,professor_id,role,kind,content,media_extracted_text,channel,wa_message_id,criado_em,fabio_seen_at,fabio_done_at"
    rows = sb_get("/rest/v1/fabio_chat_mensagens", {
        "select": select_cols,
        "role": "eq.professor",
        "fabio_seen_at": "is.null",
        "order": "criado_em.asc",
        "limit": "1",
    })
    stale_claim = False
    if not rows:
        stale_seconds = int(os.getenv("FABIO_STALE_CLAIM_SECONDS", "180"))
        stale_max_age_seconds = int(os.getenv("FABIO_STALE_CLAIM_MAX_AGE_SECONDS", "900"))
        now_utc = datetime.now(timezone.utc)
        stale_before = (now_utc - timedelta(seconds=stale_seconds)).isoformat()
        stale_after = (now_utc - timedelta(seconds=stale_max_age_seconds)).isoformat()
        rows = sb_get("/rest/v1/fabio_chat_mensagens", {
            "select": select_cols,
            "role": "eq.professor",
            "fabio_done_at": "is.null",
            "fabio_seen_at": f"lt.{stale_before}",
            "criado_em": f"gte.{stale_after}",
            "order": "criado_em.asc",
            "limit": "1",
        })
        stale_claim = bool(rows)
    if not rows:
        return None
    row = rows[0]
    filters = {"id": f"eq.{row['id']}"}
    if not stale_claim:
        filters["fabio_seen_at"] = "is.null"
    r = sb_patch(
        "/rest/v1/fabio_chat_mensagens",
        filters,
        {"fabio_seen_at": now_iso()},
        prefer="return=representation",
    )
    if r.status_code >= 400:
        raise RuntimeError(f"claim message {r.status_code}: {r.text[:500]}")
    claimed = r.json()
    if not claimed:
        return None
    if stale_claim:
        log("stale_message_reclaimed", id=row.get("id"), professor_id=row.get("professor_id"), previous_seen_at=row.get("fabio_seen_at"))
    return claimed[0] if isinstance(claimed, list) and claimed else row


