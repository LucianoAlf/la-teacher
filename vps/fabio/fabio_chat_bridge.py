def _aula_minutes(hora: str) -> Optional[int]:
    m = re.match(r"^(\d{1,2}):(\d{2})", str(hora or ""))
    if not m:
        return None
    return int(m.group(1)) * 60 + int(m.group(2))


def _today_agenda_stats(ctx: Dict[str, Any]) -> Dict[str, Any]:
    hoje = ctx.get("hoje") if isinstance(ctx.get("hoje"), dict) else {}
    aulas = hoje.get("aulas") or []
    total_aulas = hoje.get("total_aulas") or len(aulas)
    atendimentos = sum(len(a.get("alunos") or []) for a in aulas)
    chamadas_feitas = sum(1 for a in aulas if a.get("chamada_feita") is True)
    first_min = None
    last_min = None
    for aula in aulas:
        mins = _aula_minutes(aula.get("hora"))
        if mins is None:
            continue
        first_min = mins if first_min is None else min(first_min, mins)
        last_min = mins if last_min is None else max(last_min, mins)
    now = datetime.now(ZoneInfo("America/Sao_Paulo"))
    now_min = now.hour * 60 + now.minute
    phase = "sem_agenda"
    if aulas:
        if first_min is not None and now_min < first_min - 45:
            phase = "antes"
        elif last_min is not None and now_min >= last_min + 50:
            phase = "depois"
        else:
            phase = "durante"
    return {
        "aulas": aulas,
        "total_aulas": total_aulas,
        "atendimentos": atendimentos,
        "chamadas_feitas": chamadas_feitas,
        "phase": phase,
        "now_min": now_min,
    }


