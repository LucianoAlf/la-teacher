def _is_light_checkin(norm: str) -> bool:
    clean = re.sub(r"[^a-z0-9áéíóúâêôãõç\s]", " ", norm)
    clean = re.sub(r"\s+", " ", clean).strip()
    if not clean:
        return False
    tokens = clean.split()
    if len(tokens) > 8:
        return False
    allowed = {
        "oi", "ola", "olá", "opa", "fala", "coe", "coé", "salve", "qual", "é", "e", "ai", "aí",
        "bom", "boa", "dia", "tarde", "noite", "fabio", "fábio", "ta", "tá", "por",
        "aqui", "comigo", "tudo", "bem", "td", "blz", "beleza", "mano", "cara",
    }
    signal = {"oi", "ola", "olá", "opa", "fala", "coe", "coé", "salve", "qual", "fabio", "fábio", "tá", "ta", "bom", "boa"}
    return all(t in allowed for t in tokens) and any(t in signal for t in tokens)



