def sb_headers(prefer: Optional[str] = None) -> Dict[str, str]:
    if not SUPABASE_KEY:
        raise RuntimeError("LAREPORT_SUPABASE_SERVICE_ROLE missing")
    h = {
        "apikey": SUPABASE_KEY,
        "Authorization": f"Bearer {SUPABASE_KEY}",
        "Content-Type": "application/json",
    }
    if prefer:
        h["Prefer"] = prefer
    return h


def sb_get(path: str, params: Dict[str, str]) -> Any:
    r = requests.get(f"{SUPABASE_URL}{path}", headers=sb_headers(), params=params, timeout=_HTTP_TIMEOUT)
    if r.status_code >= 400:
        raise RuntimeError(f"Supabase GET {path} {r.status_code}: {r.text[:500]}")
    return r.json()


def sb_post(path: str, body: Any, prefer: Optional[str] = None) -> requests.Response:
    return requests.post(f"{SUPABASE_URL}{path}", headers=sb_headers(prefer), json=body, timeout=_HTTP_TIMEOUT)


def sb_patch(path: str, params: Dict[str, str], body: Any, prefer: Optional[str] = None) -> requests.Response:
    return requests.patch(f"{SUPABASE_URL}{path}", headers=sb_headers(prefer), params=params, json=body, timeout=_HTTP_TIMEOUT)


def get_data(body: Dict[str, Any]) -> Dict[str, Any]:
    if isinstance(body.get("messages"), list) and body["messages"]:
        return body["messages"][0] or {}
    if isinstance(body.get("message"), dict):
        return body["message"]
    if isinstance(body.get("data"), dict):
        return body["data"]
    return body


def extract_text(body: Dict[str, Any]) -> Optional[str]:
    data = get_data(body)
    value = data.get("content") or data.get("text") or data.get("body") or data.get("caption")
    if isinstance(value, dict):
        value = value.get("text") or value.get("body")
    if value is None:
        return None
    value = str(value).strip()
    return value or None


def extract_phone(body: Dict[str, Any]) -> Optional[str]:
    data = get_data(body)
    raw = data.get("chatid") or data.get("sender") or data.get("from") or data.get("remoteJid") or ""
    if "@lid" in str(raw):
        raw = body.get("chat", {}).get("wa_chatid") or raw
    phone = str(raw).split("@")[0]
    digits = re.sub(r"\D+", "", phone)
    return digits or None


def extract_message_id(body: Dict[str, Any]) -> Optional[str]:
    data = get_data(body)
    for key in ("id", "messageId", "message_id", "wa_message_id", "keyId"):
        value = data.get(key) or body.get(key)
        if value:
            return str(value)
    key = data.get("key")
    if isinstance(key, dict):
        for k in ("id", "messageId"):
            if key.get(k):
                return str(key[k])
    return None


def is_ignorable_uazapi(body: Dict[str, Any]) -> bool:
    event = body.get("EventType") or body.get("event_type") or body.get("type") or body.get("event")
    if event and str(event) != "messages":
        return True
    data = get_data(body)
    if not data:
        return True
    if data.get("wasSentByApi") is True:
        return True
    if data.get("fromMe") is True:
        return True
    if data.get("isGroup") is True:
        return True
    return False


