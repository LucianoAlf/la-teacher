    for aula in aulas:
        for aluno in aula.get("alunos") or []:
            first = str(aluno).split()[0] if aluno else ""
            if first and first not in names:
                names.append(first)
            if len(names) >= 3:
                break
        if len(names) >= 3:
            break
    if not names:
        return "algum aluno específico"
    if len(names) == 1:
        return names[0]
    return ", ".join(names[:-1]) + " ou " + names[-1]


