def _norm_text(value: Any) -> str:
    raw = str(value or "").lower()
    raw = "".join(c for c in unicodedata.normalize("NFKD", raw) if not unicodedata.combining(c))
    return re.sub(r"\s+", " ", raw).strip()


def _course_base(value: Any) -> str:
    text = _norm_text(value)
    # Emusys often adds technical suffixes such as "Canto T" or "Piano IND".
    text = re.sub(r"\b(t|ind|kids|adulto|adultos)\b", "", text)
    return re.sub(r"\s+", " ", text).strip()


def _has_pedagogical_history_intent(current_text: str, hist: list[Dict[str, Any]]) -> bool:
    recent = "\n".join((h.get("content") or "") for h in hist[-6:])
    hay = _norm_text(current_text + "\n" + recent)
    patterns = [
        "ultima aula", "ultimo conteudo", "conteudo da ultima", "relembrar",
        "o que foi feito", "o que ela fez", "o que ele fez", "trabalhou",
        "prontuario", "historico", "continuidade", "aula passada", "ultima vez",
    ]
    return any(p in hay for p in patterns)


