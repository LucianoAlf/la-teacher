def _is_light_checkin(norm: str) -> bool:
    clean = re.sub(r"[^a-z0-9áéíóúâêôãõç\s]", " ", norm)
    clean = re.sub(r"\s+", " ", clean).strip()
    if not clean:
        return False
    tokens = clean.split()
    if len(tokens) > 8:
        return False
    allowed = {
        "oi", "ola", "olá", "opa", "fala", "coe", "coé", "salve", "qual", "é", "e", "ai", "aí",
        "bom", "boa", "dia", "tarde", "noite", "fabio", "fábio", "ta", "tá", "por",
        "aqui", "comigo", "tudo", "bem", "td", "blz", "beleza", "mano", "cara",
    }
    signal = {"oi", "ola", "olá", "opa", "fala", "coe", "coé", "salve", "qual", "fabio", "fábio", "tá", "ta", "bom", "boa"}
    return all(t in allowed for t in tokens) and any(t in signal for t in tokens)



def _admin_deep_analysis_intent(row: Dict[str, Any]) -> bool:
    """Detect heavy admin analysis that should become async fan-out."""
    if (row.get("identidade_tipo") or "professor") != "admin":
        return False
    text = _norm_text(row.get("content") or row.get("media_extracted_text") or "")
    if not text:
        return False
    triggers = [
        "pente fino", "pente-fino", "faz o pente", "fazer o pente",
        "merece atencao", "merecem atencao", "precisa de atencao", "pedem atencao",
        "quem olhar primeiro", "casos que pedem", "lista curta", "sem achismo",
    ]
    return any(t in text for t in triggers)


def _unit_from_text_and_history(row: Dict[str, Any]) -> Dict[str, Any]:
    hist = recent_history_for_row(row, 8)
    hay = _norm_text("\n".join([(h.get("content") or "") for h in hist] + [row.get("content") or ""]))
    units = sb_get("/rest/v1/unidades", {"select": "id,nome,codigo", "order": "nome.asc"})
    wanted = None
    if "campo grande" in hay or re.search(r"\bcg\b", hay):
        wanted = "campo grande"
    elif "recreio" in hay or re.search(r"\brec\b", hay):
        wanted = "recreio"
    elif "barra" in hay:
        wanted = "barra"
    for u in units or []:
        if wanted and _norm_text(u.get("nome")) == wanted:
            return u
    for u in units or []:
        if _norm_text(u.get("nome")) == "campo grande":
            return u
    return (units or [{}])[0]


