def send_whatsapp_presence(phone: str, presence: str = "composing", delay_ms: Optional[int] = None) -> None:
    """Show WhatsApp presence while Hermes is generating.

    UAZAPI /message/presence is async, refreshes every 10s, and is cancelled
    automatically when /send/text sends the final message to the same chat.
    """
    if not UAZAPI_TOKEN:
        return
    if delay_ms is None:
        delay_ms = int(os.getenv("FABIO_WHATSAPP_PRESENCE_DELAY_MS", "300000"))
    delay_ms = max(0, min(int(delay_ms), 300000))
    payload = {"number": phone, "presence": presence}
    if delay_ms > 0 and presence != "paused":
        payload["delay"] = delay_ms
    r = requests.post(
        f"{UAZAPI_URL}/message/presence",
        headers={"Content-Type": "application/json", "token": UAZAPI_TOKEN},
        json=payload,
        timeout=_HTTP_TIMEOUT,
    )
    if r.status_code >= 400:
        raise RuntimeError(f"uazapi message/presence {r.status_code}: {r.text[:500]}")
    log("whatsapp_presence_sent", presence=presence, phone_tail=phone[-4:], delay_ms=delay_ms)


