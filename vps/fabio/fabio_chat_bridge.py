def uazapi_transcrever_audio(wa_message_id: str) -> Dict[str, Any]:
    """Pede a UAZAPI o audio ja transcrito.

    /message/download com transcribe=true devolve a transcricao pronta -- e o
    mesmo caminho que a edge function transcrever-mensagem-evasao usa. Nao
    temos STT proprio nem precisamos de um.
    """
    if not UAZAPI_TOKEN:
        raise RuntimeError("uazapi_token_missing")
    r = requests.post(
        f"{UAZAPI_URL}/message/download",
        headers={"Content-Type": "application/json", "token": UAZAPI_TOKEN},
        json={"id": wa_message_id, "transcribe": True, "generate_mp3": True, "return_link": True},
        timeout=_AUDIO_TIMEOUT,
    )
    if r.status_code >= 400:
        raise RuntimeError(f"uazapi message/download {r.status_code}: {r.text[:300]}")
    corpo = r.json() if r.content else {}
    if not isinstance(corpo, dict):
        raise RuntimeError("uazapi message/download resposta inesperada")
    texto = corpo.get("transcription")
    texto = str(texto).strip() if texto else ""
    return {
        "texto": texto or None,
        "url": corpo.get("fileURL") or corpo.get("fileUrl") or corpo.get("url"),
        "mime": corpo.get("mimetype") or corpo.get("mimeType"),
    }


def extract_phone(body: Dict[str, Any]) -> Optional[str]:
    data = get_data(body)
    raw = data.get("chatid") or data.get("sender") or data.get("from") or data.get("remoteJid") or ""
    if "@lid" in str(raw):
        raw = body.get("chat", {}).get("wa_chatid") or raw
    phone = str(raw).split("@")[0]
    digits = re.sub(r"\D+", "", phone)
    return digits or None


def extract_message_id(body: Dict[str, Any]) -> Optional[str]:
    data = get_data(body)
    for key in ("id", "messageId", "message_id", "wa_message_id", "keyId"):
        value = data.get(key) or body.get(key)
        if value:
            return str(value)
    key = data.get("key")
    if isinstance(key, dict):
        for k in ("id", "messageId"):
            if key.get(k):
                return str(key[k])
    return None


def is_ignorable_uazapi(body: Dict[str, Any]) -> bool:
    event = body.get("EventType") or body.get("event_type") or body.get("type") or body.get("event")
    if event and str(event) != "messages":
        return True
    data = get_data(body)
    if not data:
        return True
    if data.get("wasSentByApi") is True:
        return True
    if data.get("fromMe") is True:
        return True
    if data.get("isGroup") is True:
        return True
    return False


def resolve_identity_by_phone(phone: str) -> Dict[str, Any]:
    r = sb_post("/rest/v1/rpc/fabio_identidade_whatsapp", {"p_telefone": phone})
    if r.status_code >= 400:
        raise RuntimeError(f"fabio_identidade_whatsapp {r.status_code}: {r.text[:500]}")
    data = r.json()
    if not isinstance(data, dict) or not data.get("ok"):
        raise RuntimeError(f"identity_not_resolved: {data}")
    tipo = data.get("tipo")
    if tipo not in {"professor", "admin"}:
        raise RuntimeError(f"identity_tipo_invalid: {data}")
    return data


def resolve_professor_by_phone(phone: str) -> Dict[str, Any]:
    data = resolve_identity_by_phone(phone)
    if data.get("tipo") != "professor":
        raise RuntimeError(f"identity_is_not_professor: {data}")
    return data


def insert_identity_message(
    identity: Dict[str, Any],
    text: Optional[str],
    channel: str,
    wa_message_id: Optional[str] = None,
    kind: str = "text",
    media_url: Optional[str] = None,
    media_mime: Optional[str] = None,
    media_extracted_text: Optional[str] = None,
) -> Dict[str, Any]:
    tipo = identity.get("tipo") or "professor"
    row = {
        "identidade_tipo": tipo,
        "role": "professor",
        "kind": kind,
        "content": text,
        "channel": channel,
    }
    if media_url:
        row["media_url"] = media_url
    if media_mime:
        row["media_mime"] = media_mime
    if media_extracted_text:
        row["media_extracted_text"] = media_extracted_text
    if tipo == "admin":
        row["usuario_id"] = int(identity["usuario_id"])
    else:
        row["professor_id"] = int(identity["professor_id"])
    if wa_message_id:
        row["wa_message_id"] = wa_message_id
    r = sb_post("/rest/v1/fabio_chat_mensagens", row, prefer="return=representation")
    if r.status_code == 409:
        return {"duplicate": True, "wa_message_id": wa_message_id}
    if r.status_code >= 400:
        raise RuntimeError(f"insert chat message {r.status_code}: {r.text[:500]}")
    data = r.json()
    return data[0] if isinstance(data, list) and data else row


