def collect_admin_deep_analysis(row: Dict[str, Any]) -> Dict[str, Any]:
    """Fan-out read-only collectors for heavy admin/professor analysis."""
    unit = _unit_from_text_and_history(row)
    started = time.monotonic()
    collectors = {
        "carteira": _fetch_async_roster,
        "registros": _fetch_async_registros,
        "jornada": _fetch_async_jornada,
        "retencao_evasoes": _fetch_async_retencao,
    }
    results: Dict[str, Any] = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as ex:
        futs = {ex.submit(fn, unit): name for name, fn in collectors.items()}
        for fut in concurrent.futures.as_completed(futs, timeout=90):
            name = futs[fut]
            try:
                results[name] = fut.result()
            except Exception as e:
                results[name] = {"collector": name, "error": str(e)[:500]}
    evidence = _score_admin_deep_analysis(unit, results)
    evidence["elapsed_collect_s"] = round(time.monotonic() - started, 2)
    return evidence


def _score_admin_deep_analysis(unit: Dict[str, Any], results: Dict[str, Any]) -> Dict[str, Any]:
    professors: Dict[str, Dict[str, Any]] = {}

    def get_prof(pid: Any, name: Any = None) -> Dict[str, Any]:
        key = str(pid or _norm_text(name))
        if key not in professors:
            professors[key] = {"professor_id": pid, "professor_nome": name, "score": 0, "motivos": [], "evidencias": {}}
        if name and not professors[key].get("professor_nome"):
            professors[key]["professor_nome"] = name
        return professors[key]

    for r in (results.get("carteira") or {}).get("rows") or []:
        p = get_prof(r.get("professor_id"), r.get("professor_nome"))
        total = _int(r.get("total_alunos"))
        verm = _int(r.get("alunos_vermelhos"))
        amar = _int(r.get("alunos_amarelos"))
        sem = _int(r.get("alunos_sem_avaliacao"))
        p["evidencias"]["carteira"] = {"total_alunos": total, "vermelhos": verm, "amarelos": amar, "sem_avaliacao": sem}
        if verm:
            p["score"] += verm * 6
            p["motivos"].append(f"{verm} aluno(s) em vermelho")
        if amar:
            p["score"] += amar * 3
            p["motivos"].append(f"{amar} aluno(s) em amarelo")
        if sem >= 3:
            p["score"] += min(sem, 10)
            p["motivos"].append(f"{sem} aluno(s) sem avaliação")

    for r in (results.get("registros") or {}).get("rows") or []:
        p = get_prof(r.get("professor_id"), r.get("professor_nome"))
        aulas = _int(r.get("aulas"))
        cobertura = _num(r.get("pct_cobertura"))
        north = _num(r.get("pct_north_star"))
        cobraveis = _int(r.get("aulas_cobraveis"))
        p["evidencias"]["registros"] = {"mes": r.get("mes"), "aulas": aulas, "com_registro": _int(r.get("com_registro")), "pct_cobertura": cobertura, "pct_north_star": north, "aulas_cobraveis": cobraveis}
        if aulas >= 10 and cobertura < 30:
            p["score"] += 8
            p["motivos"].append(f"baixa cobertura de registros ({cobertura:.0f}% em {aulas} aulas no mês)")
        elif aulas >= 10 and cobertura < 60:
            p["score"] += 4
            p["motivos"].append(f"cobertura de registros intermediária ({cobertura:.0f}%)")
        if cobraveis > 0:
            p["score"] += min(cobraveis, 12)
            p["motivos"].append(f"{cobraveis} aula(s) cobráveis sem registro")

    jornada_by_prof: Dict[Any, list[Dict[str, Any]]] = {}
    for r in (results.get("jornada") or {}).get("rows") or []:
        pid = r.get("professor_id")
        jornada_by_prof.setdefault(pid, []).append(r)
        get_prof(pid, r.get("professor_nome"))
    for pid, rows in jornada_by_prof.items():
        p = get_prof(pid, rows[0].get("professor_nome") if rows else None)
        low = []
        faltas3 = []
        final_journey = []
        for r in rows:
            pct = _num(r.get("percentual_presenca_contrato"), 100)
            faltas = _int(r.get("faltas"))
            jornada = _num(r.get("percentual_jornada"))
            passadas = _int(r.get("nr_aulas_passadas"))
            if passadas >= 4 and pct < 80:
                low.append(r)
            if faltas >= 3:
                faltas3.append(r)
            if jornada >= 80 and pct < 85:
                final_journey.append(r)
        p["evidencias"]["jornada"] = {"alunos_analisados": len(rows), "presenca_baixa": len(low), "faltas_3mais": len(faltas3), "fim_jornada_com_risco": len(final_journey)}
        if low:
            p["score"] += min(len(low) * 3, 18)
            p["motivos"].append(f"{len(low)} aluno(s) com presença abaixo de 80%")
        if faltas3:
            p["score"] += min(len(faltas3) * 2, 12)
            p["motivos"].append(f"{len(faltas3)} aluno(s) com 3+ faltas")
        if final_journey:
            p["score"] += min(len(final_journey) * 3, 12)
            p["motivos"].append(f"{len(final_journey)} aluno(s) no fim da jornada com risco")

    by_name = {_norm_text(p.get("professor_nome")): p for p in professors.values() if p.get("professor_nome")}
    latest_evas_by_name = {}
    for r in (results.get("retencao_evasoes") or {}).get("evasoes") or []:
        name = _norm_text(r.get("professor"))
        if name and name not in latest_evas_by_name:
            latest_evas_by_name[name] = r
    for name, r in latest_evas_by_name.items():
        p = by_name.get(name)
        if not p:
            continue
        evas = _int(r.get("evasoes"))
        risco = str(r.get("nivel_risco") or "")
        p["evidencias"]["evasoes"] = {"ano": r.get("ano"), "evasoes": evas, "nivel_risco": risco, "taxa_renovacao": r.get("taxa_renovacao")}
        if evas > 0:
            p["score"] += min(evas * 3, 15)
            p["motivos"].append(f"{evas} evasão(ões) no recorte do ranking")
        if "alto" in _norm_text(risco):
            p["score"] += 5
            p["motivos"].append("nível de risco alto no ranking")

    ranked = [p for p in professors.values() if p.get("score", 0) > 0]
    ranked.sort(key=lambda x: (x.get("score", 0), _int((x.get("evidencias") or {}).get("carteira", {}).get("total_alunos"))), reverse=True)
    return {
        "unidade": {"id": unit.get("id"), "nome": unit.get("nome"), "codigo": unit.get("codigo")},
        "professores_analisados": len(professors),
        "top": ranked[:8],
        "collectors_ok": {k: not bool((v or {}).get("error")) for k, v in results.items()},
    }


def _fallback_admin_analysis_text(evidence: Dict[str, Any]) -> str:
    unit = (evidence.get("unidade") or {}).get("nome") or "a unidade"
    top = evidence.get("top") or []
    if not top:
        return f"Alf, fiz o pente-fino em {unit} e não apareceu nenhum alerta forte com os dados disponíveis. Eu olharia mais por rotina de coordenação do que por risco objetivo agora."
    lines = [f"Fechei o pente-fino de {unit}, Alf. Sem caça às bruxas: isso aqui é prioridade de apoio, não sentença.", ""]
    for i, p in enumerate(top[:5], 1):
        nome = p.get("professor_nome") or "Professor"
        motivos = p.get("motivos") or []
        ev = p.get("evidencias") or {}
        carteira = ev.get("carteira") or {}
        resumo = "; ".join(motivos[:3]) or "sinal misto nos indicadores"
        alunos = carteira.get("total_alunos")
        sufixo = f" — carteira: {alunos} aluno(s)" if alunos is not None else ""
        lines.append(f"{i}. *{nome}*{sufixo}. Motivo: {resumo}.")
    lines += ["", "Eu começaria pelos 3 primeiros com conversa de apoio e evidência na mão: presença, registro e aluno em risco. Não entraria como cobrança seca."]
    return "\n".join(lines)[:3900]


