def canonical_phone(value: str) -> Optional[str]:
    digits = re.sub(r"\D+", "", value or "")
    if not digits:
        return None
    if digits.startswith("55"):
        return digits
    if len(digits) in (10, 11):
        return "55" + digits
    return digits


