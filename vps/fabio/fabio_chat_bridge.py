def professor_context(professor_id: int, data: Optional[str] = None) -> Dict[str, Any]:
    """Fetch identity/agenda/context for the already-resolved professor.

    Cached for a short TTL: enough to make quick chat fluid, short enough not
    to hide schedule/context changes for long.
    """
    pid = int(professor_id)
    day = data or today_brt()
    key = (pid, day)
    now = time.time()
    cached = _CONTEXT_CACHE.get(key)
    if cached and now - cached[0] <= CONTEXT_CACHE_TTL:
        return cached[1]
    body = {"p_professor_id": pid, "p_data": day}
    r = sb_post("/rest/v1/rpc/fabio_contexto_professor", body)
    if r.status_code >= 400:
        raise RuntimeError(f"fabio_contexto_professor {r.status_code}: {r.text[:500]}")
    data_json = r.json()
    ctx = data_json if isinstance(data_json, dict) else {"ok": False, "raw": data_json}
    if ctx.get("ok"):
        _CONTEXT_CACHE[key] = (now, ctx)
    return ctx


